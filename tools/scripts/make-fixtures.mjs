import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const dataDir = join(here, '..', 'data', 'official');
const outPath = join(here, '..', '..', 'tests', 'fixtures', 'official-vectors.json');

// Big exhaustive files: sample evenly so the committed fixture stays small.
const SAMPLING = {
  'vectors_base4': 40,
  'vectors_modified4': 40,
  'vectors_random4': 40,
  'vectors_simple4': 20,
};

// Small exhaustive files: keep every vector (they cover every value of E, CR/IR/AR
// and all six supplemental metrics).
const FULL = ['vectors_threat4', 'vectors_security4', 'vectors_supplemental4'];

const entries = [];

function parseLine(line) {
  const idx = line.indexOf(' - ');
  const vector = line.slice(0, idx).trim();
  // Official files render tuples as "(9.2,)" or plain "9.2"; strip both forms.
  const score = Number(line.slice(idx + 3).trim().replace(/[(),]/g, ''));
  return { vector, score };
}

for (const [file, take] of Object.entries(SAMPLING)) {
  const lines = readFileSync(join(dataDir, file), 'utf8').split('\n').filter((l) => l.trim());
  const stride = Math.max(1, Math.floor(lines.length / take));
  for (let i = 0; i < lines.length && entries.filter((e) => e.source === file).length < take; i += stride) {
    const { vector, score } = parseLine(lines[i]);
    entries.push({ vector, expectedScore: score, source: file });
  }
}

for (const file of FULL) {
  const lines = readFileSync(join(dataDir, file), 'utf8').split('\n').filter((l) => l.trim());
  for (const line of lines) {
    const { vector, score } = parseLine(line);
    entries.push({ vector, expectedScore: score, source: file });
  }
}

writeFileSync(
  outPath,
  JSON.stringify(
    {
      note: 'Official CVSS v4.0 test vectors from RedHatProductSecurity/cvss (tests/vectors_*4), BSD-2-Clause. Generated by tools/scripts/make-fixtures.mjs.',
      generatedFrom: Object.keys({ ...SAMPLING, ...Object.fromEntries(FULL.map((f) => [f, true])) }),
      entries,
    },
    null,
    2,
  ) + '\n',
);

const bySource = new Map();
for (const e of entries) bySource.set(e.source, (bySource.get(e.source) ?? 0) + 1);
console.log(`wrote ${entries.length} vectors to ${outPath}`);
for (const [s, n] of bySource) console.log(`  ${s}: ${n}`);
