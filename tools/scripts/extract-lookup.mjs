// One-off generator: pulls the lookup tables out of the vendored FIRST/Red Hat reference
// calculator (tools/reference/cvss40.js, BSD-2-Clause) into src/lib/cvss/lookup.js so the
// scoring engine ships the same constants without depending on the reference file at runtime.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const refPath = join(here, '..', 'reference', 'cvss40.js');
const outPath = join(here, '..', '..', 'src', 'lib', 'cvss', 'lookup.js');
const src = readFileSync(refPath, 'utf8');

function extractBlock(startMarker) {
  const i = src.indexOf(startMarker);
  if (i < 0) throw new Error('marker not found: ' + startMarker);
  const start = src.indexOf('{', i);
  let depth = 0, inStr = false, quote = '', esc = false;
  for (let p = start; p < src.length; p++) {
    const c = src[p];
    if (inStr) {
      if (esc) esc = false;
      else if (c === '\\') esc = true;
      else if (c === quote) inStr = false;
      continue;
    }
    if (c === '"' || c === "'" || c === '`') { inStr = true; quote = c; continue; }
    if (c === '{') depth++;
    else if (c === '}') {
      depth--;
      if (depth === 0) return src.slice(start, p + 1);
    }
  }
  throw new Error('unbalanced block for ' + startMarker);
}

const values = {};
for (const name of ['LOOKUP_TABLE', 'METRIC_LEVELS', 'MAX_COMPOSED', 'MAX_SEVERITY']) {
  values[name] = new Function('return (' + extractBlock(`static ${name} =`) + ')')();
}

const header = `// CVSS v4.0 lookup constants, transcribed from the FIRST/Red Hat reference calculator
// (RedHatProductSecurity/cvss-v4-calculator, BSD-2-Clause), itself derived from the
// FIRST CVSS v4.0 specification (https://www.first.org/cvss/v4.0/specification-document).
// Generated by tools/extract-lookup.mjs -- do not edit by hand.

`;
const out = header +
  `export const LOOKUP_TABLE = ${JSON.stringify(values.LOOKUP_TABLE, null, 2)};\n\n` +
  `// Severity level of each metric value, used to compute severity distances.\n` +
  `export const METRIC_LEVELS = ${JSON.stringify(values.METRIC_LEVELS, null, 2)};\n\n` +
  `// Highest-severity vector fragments for each equivalency class.\n` +
  `export const MAX_COMPOSED = ${JSON.stringify(values.MAX_COMPOSED, null, 2)};\n\n` +
  `// Maximum severity distance per equivalency class (the depth of the macrovector).\n` +
  `export const MAX_SEVERITY = ${JSON.stringify(values.MAX_SEVERITY, null, 2)};\n`;

writeFileSync(outPath, out);
console.log(`wrote ${outPath} (${Object.keys(values.LOOKUP_TABLE).length} macrovectors)`);
